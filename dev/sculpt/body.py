def body_sdf(parts=('torso', 'arms', 'hands', 'legs', 'feet')):
    base, it = torso()
    if 'arms' in parts:
        for s in (-1, 1): it += arm(s)
    if 'hands' in parts:
        for s in (-1, 1): it += hand(s)
    if 'legs' in parts:
        for s in (-1, 1): it += leg(s)
    if 'feet' in parts:
        for s in (-1, 1): it += foot(s)
    f = blend(base, it)
    # flat soles
    return lambda P: smax(f(P), .002 - P[:, 1], .004)
